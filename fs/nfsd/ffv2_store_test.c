	memcpy(bytes + 244, handle, sizeof(handle));
	put_unaligned_be32(4096, bytes + 372);
	put_unaligned_be64(8, bytes + 376);
	ffv2_test_crc("FFV2-D2-WAL-v1", bytes,
		      NFSD_FFV2_FILE_REGISTER_RECORD_SIZE);
