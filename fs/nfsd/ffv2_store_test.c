#include <kunit/test.h>
#include <linux/slab.h>
#include <linux/unaligned.h>

#include "ffv2_store.h"

static void ffv2_test_fill(u8 *data, size_t len, u8 first)
{
	size_t i;

	for (i = 0; i < len; i++)
		data[i] = first + i;
}

static void ffv2_super_vector_test(struct kunit *test)
{
	struct nfsd_ffv2_super_record source = {};
	struct nfsd_ffv2_super_record decoded;
	u8 *bytes;

	bytes = kunit_kzalloc(test, NFSD_FFV2_SUPER_SLOT_SIZE, GFP_KERNEL);
	KUNIT_ASSERT_NOT_NULL(test, bytes);
	ffv2_test_fill(source.store_uuid, 16, 0x10);
	ffv2_test_fill(source.fs_uuid, 16, 0x20);
	ffv2_test_fill(source.export_uuid, 16, 0x30);
	ffv2_test_fill(source.wal_uuid, 16, 0x40);
	ffv2_test_fill(source.payload_uuid, 16, 0x50);
	ffv2_test_fill(source.binding_token_digest, 32, 0x60);
	source.generation = 2;
	source.ds_incarnation = 1;
	source.capacity_wal_bytes = NFSD_FFV2_MIN_WAL_SIZE;
	source.capacity_payload_bytes = 1U << 20;
	source.payload_durable_bytes = NFSD_FFV2_PAYLOAD_ALIGN;
	source.state = NFSD_FFV2_SUPER_CLEAN;
	source.format_floor = NFSD_FFV2_FORMAT_VERSION;

	KUNIT_ASSERT_EQ(test, nfsd_ffv2_super_encode(&source, bytes), 0);
	/* Generated by the independently implemented D2b oracle. */
	KUNIT_EXPECT_EQ(test, get_unaligned_be32(bytes + 356), 0x2c4063b3U);
	KUNIT_ASSERT_EQ(test,
			nfsd_ffv2_super_decode(bytes, source.store_uuid, &decoded),
			0);
	KUNIT_EXPECT_EQ(test, decoded.generation, source.generation);
	KUNIT_EXPECT_EQ(test, decoded.state, source.state);
	bytes[100] ^= 1;
	KUNIT_EXPECT_EQ(test,
			nfsd_ffv2_super_decode(bytes, source.store_uuid, &decoded),
			-EBADMSG);
}

static void ffv2_start_vector_test(struct kunit *test)
{
	struct nfsd_ffv2_wal_header header = {
		.family = NFSD_FFV2_WAL_START,
		.total_bytes = NFSD_FFV2_START_RECORD_SIZE,
		.lsn = 1,
		.ds_incarnation = 1,
	};
	struct nfsd_ffv2_wal_header decoded_header;
	struct nfsd_ffv2_start_record source = {
		.ds_incarnation = 1,
		.recovery_decision = NFSD_FFV2_RECOVERY_FIRST_PROVISION,
		.wal_append_cursor = NFSD_FFV2_START_RECORD_SIZE,
		.payload_append_cursor = NFSD_FFV2_PAYLOAD_ALIGN,
		.capacity_wal_bytes = NFSD_FFV2_MIN_WAL_SIZE,
		.capacity_payload_bytes = 1U << 20,
	};
	struct nfsd_ffv2_start_record decoded;
	u8 *bytes;

	bytes = kunit_kzalloc(test, NFSD_FFV2_START_RECORD_SIZE, GFP_KERNEL);
	KUNIT_ASSERT_NOT_NULL(test, bytes);
	ffv2_test_fill(header.store_uuid, 16, 0x10);
	ffv2_test_fill(header.wal_uuid, 16, 0x30);
	ffv2_test_fill(source.export_uuid, 16, 0x70);

	KUNIT_ASSERT_EQ(test, nfsd_ffv2_start_encode(&header, &source, bytes), 0);
	KUNIT_EXPECT_EQ(test, get_unaligned_be32(bytes + 193), 0x42dba834U);
	KUNIT_ASSERT_EQ(test,
			nfsd_ffv2_start_decode(bytes, NFSD_FFV2_START_RECORD_SIZE,
					       header.store_uuid, header.wal_uuid,
					       &decoded_header, &decoded),
			0);
	KUNIT_EXPECT_EQ(test, decoded.wal_append_cursor,
			NFSD_FFV2_START_RECORD_SIZE);
	bytes[68] = 1;
	KUNIT_EXPECT_EQ(test,
			nfsd_ffv2_start_decode(bytes, NFSD_FFV2_START_RECORD_SIZE,
					       header.store_uuid, header.wal_uuid,
					       &decoded_header, &decoded),
			-EBADMSG);
}

static void ffv2_payload_vectors_test(struct kunit *test)
{
	struct nfsd_ffv2_payload_header header = {};
	struct nfsd_ffv2_payload_header decoded_header;
	struct nfsd_ffv2_payload_record source = {
		.object_id = (1ULL << 40) | 7,
		.checksum_algorithm = 2,
		.checksum_len = 4,
		.content_len = 4,
	};
	struct nfsd_ffv2_payload_record decoded;
	u8 content[] = { 0x40, 0x41, 0x42, 0x43 };
	u8 *bytes;
	size_t written;
	bool content_valid;
	int error;

	bytes = kunit_kzalloc(test, NFSD_FFV2_PAYLOAD_ALIGN, GFP_KERNEL);
	KUNIT_ASSERT_NOT_NULL(test, bytes);
	ffv2_test_fill(header.store_uuid, 16, 0x10);
	ffv2_test_fill(header.payload_uuid, 16, 0x20);
	ffv2_test_fill(header.wal_uuid, 16, 0x30);
	KUNIT_ASSERT_EQ(test, nfsd_ffv2_payload_header_encode(&header, bytes), 0);
	KUNIT_EXPECT_EQ(test, get_unaligned_be32(bytes + 80), 0x51fff7ddU);
	error = nfsd_ffv2_payload_header_decode(bytes, header.store_uuid,
						&decoded_header);
	KUNIT_EXPECT_EQ(test, error, 0);

	memset(bytes, 0, NFSD_FFV2_PAYLOAD_ALIGN);
	memcpy(source.store_uuid, header.store_uuid, sizeof(source.store_uuid));
	source.content = content;
	put_unaligned_be32(0x0b9c1e25, source.checksum);
	KUNIT_ASSERT_EQ(test,
			nfsd_ffv2_payload_encode(&source, bytes,
						 NFSD_FFV2_PAYLOAD_ALIGN, &written),
			0);
	KUNIT_EXPECT_EQ(test, written, (size_t)NFSD_FFV2_PAYLOAD_ALIGN);
	KUNIT_EXPECT_EQ(test, get_unaligned_be32(bytes + 44), 0x0b9c1e25U);
	KUNIT_EXPECT_EQ(test, get_unaligned_be32(bytes + 140), 0xc58be5c5U);
	KUNIT_ASSERT_EQ(test,
			nfsd_ffv2_payload_decode(bytes, written, source.store_uuid,
						 &decoded, &content_valid),
			0);
	KUNIT_EXPECT_TRUE(test, content_valid);
	bytes[NFSD_FFV2_PAYLOAD_DATA_HEADER_SIZE] ^= 1;
	KUNIT_ASSERT_EQ(test,
			nfsd_ffv2_payload_decode(bytes, written, source.store_uuid,
						 &decoded, &content_valid),
			0);
	KUNIT_EXPECT_FALSE(test, content_valid);
}

static struct kunit_case ffv2_store_test_cases[] = {
	KUNIT_CASE(ffv2_super_vector_test),
	KUNIT_CASE(ffv2_start_vector_test),
	KUNIT_CASE(ffv2_payload_vectors_test),
	{},
};

static struct kunit_suite ffv2_store_test_suite = {
	.name = "nfsd-ffv2-store",
	.test_cases = ffv2_store_test_cases,
};

kunit_test_suite(ffv2_store_test_suite);

